"""Measure whether the combined own-rule DAG fits the existing Q8192 recipe.

This is an inventory, not a valid self-ROM placement. It counts projected
dynamic inputs, static address-ROM dependencies, fanout copies and scratch
liveness under either four-history or candidate three-history packing.
"""
import argparse
from collections import Counter
import hashlib
import json
from math import ceil
from pathlib import Path

from gacsca.fixed_rule import spatial_codec,spatial_epoch,spatial_epoch8
from gacsca.fixed_rule import stream28_holder_rule as holder
from gacsca.fixed_rule import stream28_spatial_optimized as optimized
from gacsca.fixed_rule import stream28_compact_vote_optimized as compact_optimized
from gacsca.fixed_rule import stream28_compact_vote_optimized8 as compact_optimized8
from gacsca.fixed_rule import stream28_dual_pass_optimized8 as dual_optimized8
from gacsca.fixed_rule import stream28_dual_pass_optimized20 as dual_optimized20
from gacsca.fixed_rule import stream28_spatial_projected as projected
from gacsca.fixed_rule.word_allocation_and import allocate
from gacsca.fixed_rule.wordcode_and import LIT


SPATIAL_DYNAMIC_FIELDS=(1,3,*range(spatial_codec.FIELDS-12,
                                    spatial_codec.FIELDS))
PROJECTED_OUTPUT_FIELDS=(
    *range(len(holder.STATIC),holder.FIELDS),
    *(holder.FIELDS+i for i in SPATIAL_DYNAMIC_FIELDS))
assert len(PROJECTED_OUTPUT_FIELDS)==projected.FIELDS


def check(*,compact_vote=False,eight_q=False,dual_pass=False,u20=False):
    if eight_q and not compact_vote:
        raise ValueError('8Q candidate includes in-place compact vote')
    if dual_pass and not eight_q:
        raise ValueError('dual-pass candidate uses the fixed 8Q evaluator')
    if u20 and not dual_pass:
        raise ValueError('U20 candidate requires the dual-pass rule')
    selected=(dual_optimized20 if u20 else
              dual_optimized8 if dual_pass else
              compact_optimized8 if eight_q else
              compact_optimized if compact_vote else optimized)
    program,optimizer=selected.compile_description()
    limit=spatial_epoch.ROUTE_SLOTS
    n=program.inputs
    stride=holder.FIELDS+spatial_codec.FIELDS

    def routed(wire):
        return wire<n or program.operations[wire-n][0]!=LIT

    demand=Counter()
    for opcode,a,b in program.operations:
        if opcode!=LIT:
            for operand in (a,b):
                if routed(operand):demand[operand]+=1
    # Each represented output also needs one route to its own Hold sink. The
    # projected static fields are regenerated by address and are excluded.
    for field in PROJECTED_OUTPUT_FIELDS:
        demand[program.outputs[field]]+=1
    copies=[1]*len(program.operations)
    for index in range(len(copies)-1,-1,-1):
        wire=n+index
        copies[index]=max(1,ceil(demand[wire]/limit))
        opcode,a,b=program.operations[index]
        if opcode!=LIT:
            for operand in (a,b):
                if routed(operand):demand[operand]+=copies[index]-1

    used={wire for opcode,a,b in program.operations if opcode!=LIT
          for wire in (a,b) if wire<n}
    used.update(wire for wire in program.outputs if wire<n)
    input_classes=Counter()
    for wire in used:
        field=wire%stride
        if field<holder.FIELDS:
            group=('holder_static' if field<len(holder.STATIC) else
                   'holder_dynamic')
        else:
            spatial_field=field-holder.FIELDS
            group=('spatial_dynamic' if spatial_field in
                   SPATIAL_DYNAMIC_FIELDS else
                   'spatial_static')
        input_classes[group]+=1
    assert sum(input_classes.values())==len(used)
    dynamic_inputs=(input_classes['holder_dynamic']+
                    input_classes['spatial_dynamic'])
    scratch=allocate(program).count
    history_slots=3 if compact_vote else 4
    static_inputs=(input_classes['holder_static']+
                   input_classes['spatial_static'])
    memory_recipe=(8+history_slots*dynamic_inputs+
                   2*projected.FIELDS+scratch)
    gate_sites=spatial_epoch.Q-5-memory_recipe
    gate_sites_with_static=gate_sites-static_inputs
    copies_total=sum(copies)
    raw_load=tuple(demand[wire] for wire in range(n))
    over_limit=tuple((wire,load) for wire,load in enumerate(raw_load)
                     if load>limit)
    depth=[0]*n
    layers=Counter()
    routed_operand_uses=0
    for opcode,a,b in program.operations:
        level=1 if opcode==LIT else 1+max(depth[a],depth[b])
        depth.append(level)
        layers[level]+=1
        if opcode!=LIT:
            routed_operand_uses+=int(routed(a))+int(routed(b))
    return dict(passed=True,mode='dual_pass_u20_8q' if u20 else
                'dual_pass_8q' if dual_pass else
                'compact_vote_8q' if eight_q else
                'compact_vote' if compact_vote else 'four_history',
                Q=spatial_epoch.Q,
                physical_spatial_width=(spatial_epoch8.WIDTH if eight_q else
                                        spatial_epoch.WIDTH),
                static_gate_slots=spatial_epoch.GATE_SLOTS,
                static_route_slots=spatial_epoch.ROUTE_SLOTS,
                projected_state_words=projected.FIELDS,
                full_descriptor_inputs=n,
                optimized_operations=len(program.operations),
                critical_dependency_depth=max(depth),
                peak_dependency_layer=max(layers.values()),
                routed_operand_uses_before_cloning=routed_operand_uses,
                optimized_description_sha256=program.digest(),
                typed_optimizer=optimizer,
                input_dependencies=dict(input_classes),
                gathered_dynamic_input_words=dynamic_inputs,
                static_rom_input_words=static_inputs,
                fanout_gate_copies=copies_total,
                extra_fanout_copies=copies_total-len(program.operations),
                projected_output_routes=len(PROJECTED_OUTPUT_FIELDS),
                raw_inputs_over_route_limit=over_limit,
                scratch_words_current_allocator=scratch,
                history_slots_per_dynamic_input=history_slots,
                memory_recipe_words=memory_recipe,
                gate_sites_after_recipe=gate_sites,
                gate_slots_after_recipe=gate_sites*spatial_epoch.GATE_SLOTS,
                gate_slot_deficit=max(0,copies_total-
                                      gate_sites*spatial_epoch.GATE_SLOTS),
                gate_slots_if_all_static_words_occupy_sites=(
                    gate_sites_with_static*spatial_epoch.GATE_SLOTS),
                gate_slot_margin_if_static_words_occupy_sites=(
                    gate_sites_with_static*spatial_epoch.GATE_SLOTS-
                    copies_total),
                omitted_from_recipe='Static ROM lookup mechanism, address '
                                    'generation, and any buffers for raw '
                                    'sources exceeding 38 routes',
                limitation='Analytical packing inventory under selected '
                           'history and scratch recipe; no placed ROM, '
                           'fixed-point self-description, or routed schedule.')


if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output',type=Path)
    parser.add_argument('--compact-vote',action='store_true')
    parser.add_argument('--eight-q',action='store_true')
    parser.add_argument('--dual-pass',action='store_true')
    parser.add_argument('--u20',action='store_true')
    args=parser.parse_args()
    result=check(compact_vote=args.compact_vote,eight_q=args.eight_q,
                 dual_pass=args.dual_pass,u20=args.u20)
    result['source_sha256']=hashlib.sha256(Path(__file__).read_bytes()).hexdigest()
    print(json.dumps(result,indent=2))
    if args.output:
        if args.output.exists():raise FileExistsError(args.output)
        args.output.write_text(json.dumps(result,indent=2)+'\n')
