    a.branch(0, 'io_valid')
    a.label('io_word_guard')
    a.get(LENGTH)
    a.branch(2, 'cpu_fail')
    a.branch(0, 'io_valid')
    a.label('io_bit_guard')
    lane_guard(a, 8)
    a.label('io_valid')
    seek_virtual(a, VSTART, 'io')
    a.get(CTRL)
    a.immediate('shr', 11)
    a.immediate('eq', b.WRITE_BIT)
    a.branch(2, 'io_write')
    a.get(CTRL)
    a.immediate('shr', 11)
    a.immediate('eq', b.READ_WORD)
    a.branch(2, 'io_word')
    a.get(CTRL)
    a.immediate('shr', 11)
    a.immediate('eq', b.READ_BIT)
    a.branch(2, 'io_bit')
    constant_store(a, ADDRESS, 0)
    a.call('virtual_vote')
    a.branch(0, 'io_value')
    a.label('io_word')
    temporal_at_zero(a)
    a.put(TEMP)
    a.branch(0, 'io_value')
    a.label('io_bit')
    consume_raw_bit(a)
    a.put(TEMP)
    a.label('io_value')
    head_write(a, HEAD_OFFSET['a'], 20, TEMP)
    virtual_continue(a, VRET)


    a.label('io_write')
    write_virtual_output_bit(a, VA)
    virtual_continue(a, VRET)

    a.label('cpu_span')
    pending_metadata(a)
    a.get(CTRL)
    a.immediate('shr', 11)
    a.branch(1, 'span_stride_one')
    constant_store(a, ADDRESS, 5)
    a.branch(0, 'span_stride')
    a.label('span_stride_one')
    constant_store(a, ADDRESS, 1)
    a.label('span_stride')
    a.get(CTRL)
    a.immediate('shr', 11)
    a.immediate('eq', 1)
    a.branch(2, 'span_guard4')
    a.get(CTRL)
    a.immediate('shr', 11)
    a.immediate('eq', 2)
    a.branch(2, 'span_guard6')
    lane_guard(a, 8)
    a.branch(0, 'span_guard_done')
    a.label('span_guard4')
    lane_guard(a, 4)
    a.branch(0, 'span_guard_done')
    a.label('span_guard6')
    lane_guard(a, 6)
    a.label('span_guard_done')
