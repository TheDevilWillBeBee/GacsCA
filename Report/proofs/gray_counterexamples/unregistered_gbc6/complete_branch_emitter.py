def entry_move_header(a, mode):
    a.get(VB)
    a.emit('SWAP')
    a.get(VADDR)
    a.emit('ALU', b.ALU['eq'])
    a.branch(2, 'entry_'+str(mode)+'_still')
    a.get(VB)
    a.emit('SWAP')
    a.get(VADDR)
    a.emit('ALU', b.ALU['lt'])
    a.branch(2, 'entry_'+str(mode)+'_right')
    a.literal(1+4+8*mode)
    a.branch(0, 'entry_'+str(mode)+'_header')
    a.label('entry_'+str(mode)+'_right')
    a.literal(1+2+8*mode)
    a.branch(0, 'entry_'+str(mode)+'_header')
    a.label('entry_'+str(mode)+'_still')
    a.literal(1+8*mode)
    a.label('entry_'+str(mode)+'_header')
    head_write(a, 0, 6)
    a.branch(0, 'cpu_next')


def entry_lane(a):
    """LENGTH encoded lane5; sentinel16 resolves old fn4 exactly."""
    a.get(LENGTH)
    a.immediate('eq', 16)
    a.branch(1, 'entry_lane_literal')
    a.get(CTRL)
    a.immediate('shr', 7)
    a.immediate('and', 15)
    a.immediate('xor', 8)
    a.immediate('sub', 8)
    a.immediate('and', 31)
    a.put(LENGTH)
    a.label('entry_lane_literal')
    a.get(LENGTH)
    a.immediate('xor', 16)
    a.immediate('sub', 16)
    a.put(LENGTH)


def patch_pending_common(a):
    head_write(a, HEAD_OFFSET['start'], 13, VB)
    head_write(a, HEAD_OFFSET['ret'], 13, VPC)
    head_write(a, HEAD_OFFSET['lane'], 5, VRET)


def entry_guard(a, maximum, strideword):
    a.get(VPC)
    a.immediate('lt', b.Q)
    a.branch(1, 'cpu_fail')
    a.get(VB)
    a.immediate('lt', b.Q)
    a.branch(1, 'cpu_fail')
    a.get(VA)
    a.branch(1, 'cpu_fail')
    a.immediate('lt', maximum+1)
    a.branch(1, 'cpu_fail')
    a.get(VA)
    a.immediate('sub', 1)
    a.emit('SWAP')
    a.get(strideword)
    a.emit('ALU', b.ALU['mul'])
    a.emit('SWAP')
    a.get(VB)
    a.emit('ALU', b.ALU['add'])
    a.immediate('lt', b.Q)
    a.branch(1, 'cpu_fail')


def emit_entry_opcodes(a):
    emit_register_opcodes(a)
    a.label('cpu_call_entry')
    virtual_fetch(a,11)
    a.immediate('and',b.Q-1)
    a.put(VRET)
    virtual_fetch(a,24)
    a.immediate('and',1)
    a.put(TEMP)
    add_virtual_pc(a,25)
    a.get(VPC)
    a.immediate('lt',b.Q)
    a.branch(1,'cpu_fail')
    a.get(TEMP)
    a.branch(1,'call_bank0')
    head_write(a,HEAD_OFFSET['work']+380,20,VPC)
    a.branch(0,'call_stored')
    a.label('call_bank0')
    head_write(a,HEAD_OFFSET['work']+360,20,VPC)
    a.label('call_stored')
    virtual_continue(a,VRET)

    a.label('cpu_putword_entry')
    virtual_fetch(a, 11)
    a.immediate('and', 31)
    a.put(VINDEX)  # explicit width, or0 descriptor.
    virtual_fetch(a, 16)
    a.immediate('and', 1)
    a.put(VRET)  # stride kind retained separately.
    a.get(VINDEX)
    a.branch(2, 'putword_fixed')
    a.get(VB)
    a.immediate('lt', 1<<18)
    a.branch(1, 'cpu_fail')
    a.get(VB)
    a.immediate('shr', 13)
    a.immediate('and', 31)
    a.put(VINDEX)
    a.get(VB)
    a.immediate('and', b.Q-1)
    a.put(VB)
    a.label('putword_fixed')
    a.get(VINDEX)
    a.branch(1, 'cpu_fail')
    a.immediate('lt', 21)
    a.branch(1, 'cpu_fail')
    a.get(VB)
    a.immediate('lt', b.Q)
    a.branch(1, 'cpu_fail')
    a.get(VRET)
    a.immediate('mul', 4)
    a.immediate('add', 1)
    a.put(ADDRESS)
    a.get(VINDEX)
    a.immediate('sub', 1)
    a.emit('SWAP')
    a.get(ADDRESS)
    a.emit('ALU', b.ALU['mul'])
    a.emit('SWAP')
    a.get(VB)
    a.emit('ALU', b.ALU['add'])
    a.immediate('lt', b.Q)
    a.branch(1, 'cpu_fail')
    add_virtual_pc(a, 17)
    a.get(VPC)
    a.immediate('lt', b.Q)
    a.branch(1, 'cpu_fail')
    head_write(a, HEAD_OFFSET['start'], 13, VB)
    head_write(a, HEAD_OFFSET['ret'], 13, VPC)
    head_write(a, HEAD_OFFSET['kind'], 2, VRET)
    a.get(VINDEX)
    a.immediate('sub', 1)
    head_write(a, HEAD_OFFSET['index'], 13)
    head_write(a, HEAD_OFFSET['b'], 20, VA)
    entry_move_header(a, b.WORDOUT)

    a.label('cpu_read')
    virtual_fetch(a, 4)
    a.immediate('and', 3)
    a.put(VSTART)  # kind
    virtual_fetch(a, 6)
    a.immediate('and', 31)
    a.put(LENGTH)
    # All READ kinds share exactly one lane resolution block.
    a.branch(0, 'read_lane')
    a.label('cpu_write')
    constant_store(a, VSTART, 3)
    constant_store(a, LENGTH, 0)
    add_virtual_pc(a, 4)
    a.branch(0, 'write_entry_validity')
    a.label('read_lane')
    entry_lane(a)
    a.get(VSTART)
    a.immediate('eq', 3)
    a.branch(2, 'read_span_entry')
    add_virtual_pc(a, 11)
    a.get(VSTART)
    a.immediate('eq', b.READ_WORD)
    a.branch(2, 'read_word_entry_guard')
    a.get(VSTART)
    a.immediate('eq', b.READ_BIT)
    a.branch(2, 'read_bit_entry_guard')
    lane_guard(a, 6)
    a.branch(0, 'write_entry_validity')
    a.label('read_word_entry_guard')
    a.get(LENGTH)
    a.branch(2, 'cpu_fail')
    a.branch(0, 'write_entry_validity')
    a.label('read_bit_entry_guard')
    lane_guard(a, 8)
    a.label('write_entry_validity')
    a.get(VB)
    a.immediate('lt', b.Q)
    a.branch(1, 'cpu_fail')
    a.get(VPC)
    a.immediate('lt', b.Q)
    a.branch(1, 'cpu_fail')
    a.get(LENGTH)
    a.immediate('and', 31)
    a.put(VRET)
    patch_pending_common(a)
    head_write(a, HEAD_OFFSET['kind'], 2, VSTART)
    entry_move_header(a, b.IO)
    a.label('read_span_entry')
    virtual_fetch(a, 11)
    a.immediate('and', 3)
    a.put(VSTART)  # actual variant
    add_virtual_pc(a, 13)
    a.get(VSTART)
    a.branch(1, 'span_entry_stride_one')
    constant_store(a, ADDRESS, 5)
    a.branch(0, 'span_entry_stride')
    a.label('span_entry_stride_one')
    constant_store(a, ADDRESS, 1)
    a.label('span_entry_stride')
    a.get(VSTART)
    a.immediate('eq', 1)
    a.branch(2, 'span_entry_guard4')
    a.get(VSTART)
    a.immediate('eq', 2)
    a.branch(2, 'span_entry_guard6')
    lane_guard(a, 8)
    a.branch(0, 'span_entry_guard_done')
    a.label('span_entry_guard4')
    lane_guard(a, 4)
    a.branch(0, 'span_entry_guard_done')
    a.label('span_entry_guard6')
    lane_guard(a, 6)
    a.label('span_entry_guard_done')
