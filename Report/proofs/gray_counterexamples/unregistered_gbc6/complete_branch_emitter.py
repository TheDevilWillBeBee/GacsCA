"""GBC6 shared field/control emission; no own-beta claim until certified.

The executable helpers below are generic physical routines. No helper
evaluates a host transition or bypasses READ/WRITE travel. This file is
intentionally marked incomplete until all stage/CPU/source paths exist.
"""
import compact_completion_rule as b

COMPLETE_OWN_EMITTER = False
# Counted software locations inside the existing 407-bit mutable Work.
VALUE, ADDRESS, LENGTH, RETURN = 300, 320, 340, 360
assert RETURN + 20 <= b.WORK_BITS


class Assembler:
    def __init__(self):
        self.rows = []
        self.marks = {}

    def label(self, name):
        assert name not in self.marks
        self.marks[name] = len(self.rows)

    def emit(self, name, *args):
        self.rows.append((name, args))

    def literal(self, value):
        self.emit('LIT', value)

    def immediate(self, name, value):
        self.emit('ALUI', b.ALU[name], value)

    def get(self, offset):
        assert offset % 20 == 0 and 0 <= offset < 407
        self.emit('WGET', offset//20)

    def put(self, offset):
        # Preserve A, replacing precisely this counted 20-bit Work word.
        assert offset % 20 == 0 and 0 <= offset < 407
        self.emit('WSET', offset//20)

    def branch(self, condition, target):
        self.emit('BR', condition, target)

    def call(self, target, slot=RETURN):
        """Generic CALL, with both return words counted inside Work407."""
        assert slot in (360,380)
        self.emit('CALL',target,(slot-360)//20)

    def finish(self, require_fit=True):
        starts = []
        address = 0
        for name, args in self.rows:
            starts.append(address)
            address += len(b.encode(name, *(0 if isinstance(x, str) else x for x in args)))
        labels = {name: starts[index] if index < len(starts) else address
                  for name, index in self.marks.items()}
        bits, listing = [], []
        invalid = []
        for name, args in self.rows:
            values = tuple(labels[x] if isinstance(x, str) else x for x in args)
            # A rejected listing remains exact, with every out-of-range
            # branch counted. No wrapped beta is represented as valid code.
            target_index=1 if name=='BR' else 0
            bad = name in ('BR','CALL') and not 0 <= values[target_index] < b.Q
            if bad:
                invalid.append((len(bits), name, values))
            wrapped=list(values)
            if bad:wrapped[target_index]%=b.Q
            encoded = b.encode(name, *wrapped)
            listing.append((len(bits), name, values, len(encoded)))
            bits.extend(encoded)
        self.rejected_references = invalid
        self.label_addresses = labels
        if require_fit and (address > b.CODE_BITS or invalid):
            raise ValueError(('specified complete GBC6 emission rejected',
                              address, b.CODE_BITS, len(invalid)))
        return tuple(bits + [0] * max(0, b.CODE_BITS - len(bits))), listing, address


def write_word_helper(a):
    """Write low LENGTH bits of VALUE at ADDRESS, stride five.

    Caller premises: 1<=LENGTH<=20 and the whole target span is in [0,Q).
    All real I/O issue, travel, consume and return ticks are retained.
    No prepared invariant is asserted for arbitrary corrupt helper entry.
    Such entries still have total underlying local ISA semantics.
    """
    a.label('write_word')
    a.get(LENGTH)
    a.immediate('shl', 13)
    a.emit('SWAP')
    a.get(ADDRESS)
    a.emit('ALU', b.ALU['or'])
    a.emit('SWAP')
    a.get(VALUE)
    a.emit('PUTWORD', 0, 1)
    # B is now the original VALUE shifted LENGTH times, matching the
    # previous bit-loop helper's retained scratch postcondition.
    a.emit('SWAP')
    a.put(VALUE)
    a.get(LENGTH)
    a.immediate('mul', 5)
    a.emit('SWAP')
    a.get(ADDRESS)
    a.emit('ALU', b.ALU['add'])
    a.put(ADDRESS)
    a.literal(0)
    a.put(LENGTH)
    a.emit('RETURN',0)


def emit_helper_test(value, target, length):
    """Actual generic routine diagnostic, explicitly not an own beta."""
    assert 0 <= value <= b.MASK and 1 <= length <= 20
    assert 0 <= target and target + 5 * (length - 1) < b.Q
    a = Assembler()
    for offset, v in ((VALUE, value), (ADDRESS, target), (LENGTH, length)):
        a.literal(v)
        a.put(offset)
    a.call('write_word')
    a.emit('HLT')
    write_word_helper(a)
    return a.finish()


# Early-stage compiler context, all contained in the same 407-bit Work.
T, GF, FLAG1, RAWGF = 0, 20, 40, 80
COPY, STAGE, HISTORY_BASE, DISTANCE = 100, 120, 140, 160
SOURCE, DESTINATION, COPY_RETURN = 180, 200, 380
assert COPY_RETURN + 20 <= b.WORK_BITS


def constant_store(a, offset, value):
    a.literal(value)
    a.put(offset)


def emit_native_and_context(a):
    """Actual eleven-lane input loop; central native outputs and context."""
    P = b.PRIMARY_START
    a.literal(P+36)
    a.emit('SWAP')
    a.label('native_input')
    a.emit('READ', b.READ_WORD, 0)
    a.immediate('shr', 3)
    a.emit('PUSH', 11)
    a.emit('SELF', 0)
    a.immediate('eq', P)
    a.branch(2, 'native_loaded')
    a.emit('SELF', 0)
    a.immediate('sub', 1)
    a.emit('SWAP')
    a.branch(0, 'native_input')
    a.label('native_loaded')
    a.emit('NATIVE')
    a.literal(P)
    a.emit('SWAP')
    a.label('native_output')
    a.emit('SWAP')
    a.immediate('sub', P)
    a.emit('SWAP')
    a.emit('NCGET')
    a.immediate('and', 1)
    a.emit('SWAP')
    a.immediate('add', P)
    a.emit('SWAP')
    a.emit('WRITE')
    a.emit('SELF', 0)
    a.immediate('eq', P+34)
    a.branch(2, 'native_done')
    a.emit('SELF', 0)
    a.immediate('add', 1)
    a.emit('SWAP')
    a.branch(0, 'native_output')
    a.label('native_done')
    for target in (P+35, P+36):
        a.literal(target)
        a.emit('SWAP')
        a.literal(0)
        a.emit('WRITE')
    for offset, bit, mask in ((T, 13, b.MASK), (GF, 0, b.Q-1), (FLAG1, 33, 1)):
        a.literal(bit)
        a.emit('SWAP')
        a.emit('NCGET')
        a.immediate('and', mask)
        a.put(offset)


def stream_field(a, field, centre=0):
    start, count = b.offsets()[field]
    a.literal(start)
    a.emit('SWAP')
    a.literal(count)
    a.emit('STREAM', 1, 0, centre & 31)


def fill_field(a, field):
    start, count = b.offsets()[field]
    a.literal(start)
    a.emit('SWAP')
    a.literal(count)
    a.emit('FILL', 0, 0)


def copy_group_helper(a):
    """Voted five-copy one-bit source group to a different output group."""
    a.label('copy_group')
    constant_store(a, COPY, 0)
    a.label('copy_loop')
    a.get(COPY)
    a.emit('SWAP')
    a.get(SOURCE)
    a.emit('ALU', b.ALU['add'])
    a.emit('SWAP')
    a.literal(1)
    a.emit('READ', 3, 0, 1)
    a.put(VALUE)
    a.get(COPY)
    a.emit('SWAP')
    a.get(DESTINATION)
    a.emit('ALU', b.ALU['add'])
    a.put(ADDRESS)
    constant_store(a, LENGTH, 1)
    a.call('write_word')
    a.get(COPY)
    a.immediate('add', 1)
    a.put(COPY)
    a.immediate('lt', 5)
    a.branch(2, 'copy_loop')
    a.emit('RETURN',1)


def copy_fixed_group(a, source, destination):
    constant_store(a, SOURCE, source)
    constant_store(a, DESTINATION, destination)
    a.call('copy_group', COPY_RETURN)


def emit_early_stage_programme(a=None, complete=False):
    """Actual early-stage correction beta, not the complete own emitter.

    It covers every raw upper input whose computed native Age lies in
    [0,72Q+2]. Later early collection/courier/Workspace/CPU stages are
    explicitly unfinished, with a separate unsupported HLT path.
    """
    a = Assembler() if a is None else a
    emit_native_and_context(a)
    if not complete:
        a.get(T)
        a.immediate('lt', b.COLLECT)
        a.branch(2, 'early_supported')
        a.emit('HLT')
        a.label('early_supported')
    # The raw-GF wipe is computed before any SF write. Native padding is
    # absent in this binary alphabet; all input GF13 values remain raw.
    a.literal(b.PRIMARY_START)
    a.emit('SWAP')
    a.literal(13)
    a.emit('READ', 3, 0, 0)
    a.put(RAWGF)
    a.get(GF)
    a.emit('SWAP')
    a.get(RAWGF)
    a.emit('ALU', b.ALU['eq'])
    a.branch(2, 'no_wipe')
    a.get(FLAG1)
    a.branch(2, 'wipe_all')
    a.label('no_wipe')
    for field, _ in b.FIELDS:
        stream_field(a, field)
    # Reset private outputs; at age0 commit old Next into Info first.
    for age in (sorted(b.RESET) if complete else (0, 32*b.Q, 64*b.Q)):
        a.get(T)
        a.immediate('eq', age)
        a.branch(2, 'private_reset')
    a.branch(0, 'after_private_reset')
    a.label('private_reset')
    for field in ('head', 'next', 'courierL', 'courierR'):
        fill_field(a, field)
    a.get(T)
    a.branch(2, 'after_private_reset')
    copy_fixed_group(a, b.offsets()['next'][0], b.offsets()['info'][0])
    a.label('after_private_reset')
    # Mail reset/Flag1 erasure precedes loads and movements.
    a.get(FLAG1)
    a.branch(2, 'mail_zero')
    for age in (sorted(b.RESET) if complete else (0, 32*b.Q, 64*b.Q)):
        a.get(T)
        a.immediate('eq', age)
        a.branch(2, 'mail_zero')
    for age in (1, 32*b.Q+1, 64*b.Q+1):
        a.get(T)
        a.immediate('eq', age)
        a.branch(2, 'mail_load')
    if complete:
        a.get(T)
        a.immediate('lt', 80*b.Q)
        a.branch(1, 'mail_done')
    a.get(T)
    a.immediate('mod', 32*b.Q)
    a.immediate('lt', 16*b.Q)
    a.branch(2, 'mail_shift')
    a.branch(0, 'mail_done')
    a.label('mail_zero')
    fill_field(a, 'mailL')
    fill_field(a, 'mailR')
    a.branch(0, 'mail_done')
    a.label('mail_load')
    copy_fixed_group(a, b.offsets()['info'][0], b.offsets()['mailL'][0])
    copy_fixed_group(a, b.offsets()['info'][0], b.offsets()['mailR'][0])
    a.branch(0, 'mail_done')
    a.label('mail_shift')
    stream_field(a, 'mailL', 1)
    stream_field(a, 'mailR', -1)
    a.label('mail_done')
    constant_store(a, STAGE, 0)
    a.label('history_stage')
    # stage base is 32*stage*Q; retain it in DISTANCE temporarily.
    a.get(STAGE)
    a.immediate('mul', 32*b.Q)
    a.put(DISTANCE)
    a.get(STAGE)
    a.immediate('mul', 85)
    a.immediate('add', b.offsets()['history1'][0])
    a.put(HISTORY_BASE)
    # Bank g resets at ages 0,32Q,...,32gQ.
    a.get(DISTANCE)
    a.emit('SWAP')
    a.get(T)
    a.emit('ALU', b.ALU['lt'])
    a.branch(2, 'history_reset_mod')
    a.get(T)
    a.emit('SWAP')
    a.get(DISTANCE)
    a.emit('ALU', b.ALU['eq'])
    a.branch(2, 'history_reset_mod')
    a.branch(0, 'history_capture')
    a.label('history_reset_mod')
    a.get(T)
    a.immediate('mod', 32*b.Q)
    a.branch(2, 'history_capture')
    a.get(HISTORY_BASE)
    a.emit('SWAP')
    a.literal(85)
    a.emit('FILL', 0, 0)
    a.branch(0, 'history_next')
    a.label('history_capture')
    a.get(DISTANCE)
    a.immediate('add', 1)
    a.emit('SWAP')
    a.get(T)
    a.emit('ALU', b.ALU['eq'])
    a.branch(2, 'history_center')
    a.get(DISTANCE)
    a.immediate('add', 2)
    a.emit('SWAP')
    a.get(T)
    a.emit('ALU', b.ALU['sub'])
    a.put(DISTANCE)
    a.immediate('mod', b.Q)
    a.branch(2, 'history_next')
    a.get(DISTANCE)
    a.immediate('div', b.Q)
    a.put(DISTANCE)
    a.branch(1, 'history_next')
    a.immediate('lt', 9)
    a.branch(1, 'history_next')
    # The two symmetric lanes capture different OLD Mail fields.
    constant_store(a, SOURCE, b.offsets()['mailL'][0])
    a.get(DISTANCE)
    a.immediate('add', 8)
    a.immediate('mul', 5)
    a.emit('SWAP')
    a.get(HISTORY_BASE)
    a.emit('ALU', b.ALU['add'])
    a.put(DESTINATION)
    a.call('copy_group', COPY_RETURN)
    constant_store(a, SOURCE, b.offsets()['mailR'][0])
    a.get(DISTANCE)
    a.emit('SWAP')
    a.literal(8)
    a.emit('ALU', b.ALU['sub'])
    a.immediate('mul', 5)
    a.emit('SWAP')
    a.get(HISTORY_BASE)
    a.emit('ALU', b.ALU['add'])
    a.put(DESTINATION)
    a.call('copy_group', COPY_RETURN)
    a.branch(0, 'history_next')
    a.label('history_center')
    constant_store(a, SOURCE, b.offsets()['info'][0])
    a.get(HISTORY_BASE)
    a.immediate('add', 40)
    a.put(DESTINATION)
    a.call('copy_group', COPY_RETURN)
    a.label('history_next')
    a.get(STAGE)
    a.immediate('add', 1)
    a.put(STAGE)
    a.immediate('lt', 3)
    a.branch(2, 'history_stage')
    a.branch(0, 'complete_after_history') if complete else a.emit('HLT')
    a.label('wipe_all')
    start = b.PRIMARY_START+37
    a.literal(start)
    a.emit('SWAP')
    a.literal(b.FRAME_BITS-37)
    a.emit('FILL', 0, 0)
    a.emit('HLT')
    if complete:
        return a
    copy_group_helper(a)
    write_word_helper(a)
    return a.finish()


# Complete-emission context. These reuse the old stage words only after
# stage capture is finished. Software returns remain at360 and380.
CTRL, TEMP, RAW = 0, 40, 80
QCOL, CENTRE, HEADER, VADDR = 100, 120, 140, 160
VPC, VA, VB, VSTART, VRET, VINDEX = 180, 200, 220, 240, 260, 280
HEAD_BASE = b.offsets()['head'][0]
NEXT_BASE = b.offsets()['next'][0]
HEAD_OFFSET = {}
_o = 0
for _f, _w in b.META:
    HEAD_OFFSET[_f] = _o
    _o += _w
assert _o == 553 and HEAD_BASE % 5 == 0


def target_column(a, base, word=QCOL):
    a.get(word)
    a.immediate('add', base)
    a.emit('SWAP')


def head_read(a, offset, width, destination=None, centre=None):
    """Read real old five-holder Head bits at raw copy column QCOL.

    The selected centre is a signed relative logical source, not the
    physical CPU position. READ-SPAN moves on real input columns.
    """
    if centre is None:
        a.get(CENTRE)
    else:
        a.literal(centre & 15)
    a.emit('SETFN')
    assert 0<=offset<1024 and 1<=width<=20 and offset+width<=b.HEAD_BITS
    a.literal(offset+(width<<10))
    a.emit('SWAP')  # B is the descriptor; CALL preserves it.
    a.call('shared_head_read',COPY_RETURN)
    a.get(RAW)
    if destination is not None:
        a.put(destination)


def shared_head_read_helper(a):
    """Generic declared Head-window software; raw History access unchanged.

    B=offset10|width5<<10; physicalFn selects old source, q=QCOL.
    Preconditions are supplied by emitted constants. RAW80 is scratch
    and returned data, Work380 is the sole return word. Other Work,
    including live TEMP/LENGTH/ADDRESS, is preserved.
    """
    a.label('shared_head_read')
    a.emit('SWAP')
    a.put(RAW)
    a.immediate('and',1023)
    a.immediate('mul',5)
    a.immediate('add',HEAD_BASE)
    a.emit('SWAP')
    a.get(QCOL)
    a.emit('ALU',b.ALU['add'])
    a.emit('SWAP')
    a.get(RAW)
    a.immediate('shr',10)
    a.emit('READ',3,16,1)
    a.put(RAW)
    a.emit('RETURN',1)


def head_write(a, offset, width, source=None):
    if source is not None:
        a.get(source)
    a.emit('SWAP')
    a.get(QCOL)
    a.immediate('add', HEAD_BASE + 5*offset)
    a.emit('SWAP')
    a.emit('PUTWORD', width, 1)


def head_fill(a, offset, width, value=0):
    target_column(a, HEAD_BASE+5*offset)
    a.literal(width)
    a.emit('FILL', 1, value)


def head_template(a):
    a.get(CENTRE)
    a.emit('SETFN')
    target_column(a, HEAD_BASE)
    a.literal(b.HEAD_BITS)
    a.emit('STREAM', 1, 1, 16)


def service_address(a, prefix='service'):
    """(computed central GF + SLOTS[raw copy column]) moduloQ."""
    a.get(QCOL)
    a.branch(1, prefix+'_zero')
    a.immediate('lt', 3)
    a.branch(2, prefix+'_left')
    a.get(QCOL)
    a.immediate('sub', 2)
    a.branch(0, prefix+'_offset')
    a.label(prefix+'_left')
    a.get(QCOL)
    a.immediate('sub', 3)
    a.branch(0, prefix+'_offset')
    a.label(prefix+'_zero')
    a.literal(0)
    a.label(prefix+'_offset')
    a.emit('SWAP')
    a.get(GF)
    a.emit('ALU', b.ALU['add'])
    a.immediate('and', b.Q-1)
    a.put(VADDR)


def get_bit(a, word, bit):
    a.get(word)
    if bit:
        a.immediate('shr', bit)
    a.immediate('and', 1)


def read_temporal_helper(a):
    """Three OLD History banks at logical centre physicalFn, q=QCOL.

    The source centre is carried in physicalFn across real READ-SPAN;
    neither a head-centre substitution nor a host memory fetch occurs.
    TEMP/RAW/ADDRESS are scratch, return380; VALUE is temporalWord17.
    """
    a.label('temporal_word')
    for i, field in enumerate(('history1', 'history2', 'history3')):
        target_column(a, b.offsets()[field][0])
        a.literal(17)
        a.emit('READ', 3, 16, 1)
        a.put((TEMP, RAW, ADDRESS)[i])
    a.get(TEMP)
    a.emit('SWAP')
    a.get(RAW)
    a.emit('ALU', b.ALU['and'])
    a.put(VALUE)
    a.get(TEMP)
    a.emit('SWAP')
    a.get(ADDRESS)
    a.emit('ALU', b.ALU['and'])
    a.emit('SWAP')
    a.get(VALUE)
    a.emit('ALU', b.ALU['or'])
    a.put(VALUE)
    a.get(RAW)
    a.emit('SWAP')
    a.get(ADDRESS)
    a.emit('ALU', b.ALU['and'])
    a.emit('SWAP')
    a.get(VALUE)
    a.emit('ALU', b.ALU['or'])
    a.put(VALUE)
    a.emit('RETURN',1)


def virtual_fail(a):
    a.literal(25)  # p=1,move=0,mode=ERROR3.
    head_write(a, 0, 6)
    a.branch(0, 'cpu_next')


def virtual_continue(a, source=VPC):
    # Data changes precede PC validity, exactly as continue_pc.
    a.get(source)
    a.immediate('lt', b.Q)
    a.branch(1, 'cpu_fail')
    head_write(a, HEAD_OFFSET['pc'], 13, source)
    a.literal(1)
    head_write(a, 0, 6)
    a.branch(0, 'cpu_next')


def patch_move(a, move):
    a.get(HEADER)
    a.immediate('and', 57)
    a.immediate('or', 2*move)
    head_write(a, 0, 6)
    a.branch(0, 'cpu_next')


def read_virtual_metadata(a):
    # Each value is read from old selected Head, before output writes.
    for field, destination in (('pc', VPC), ('a', VA), ('b', VB)):
        head_read(a, HEAD_OFFSET[field], dict(b.META)[field], destination)
    head_read(a, HEAD_OFFSET['buf'], 13, CTRL)


def select_virtual_head(a):
    """Physical five-holder incoming priority, including every collision."""
    constant_store(a, VINDEX, 0)  # number eligible
    for k, c in enumerate((0, -1, 1)):
        label = 'incoming_' + str(k)
        head_read(a, 0, 6, TEMP, c)
        a.immediate('and', 1)
        a.branch(1, label+'_done')
        a.get(TEMP)
        a.immediate('shr', 1)
        a.immediate('and', 3)
        if c == 0:
            a.branch(1, label+'_eligible')
            a.immediate('eq', 3)
        else:
            a.immediate('eq', 1 if c == -1 else 2)
        a.branch(1, label+'_done')
        a.label(label+'_eligible')
        a.get(VINDEX)
        a.branch(2, label+'_count')
        a.get(TEMP)
        a.put(HEADER)
        constant_store(a, CENTRE, c & 15)
        a.label(label+'_count')
        a.get(VINDEX)
        a.immediate('add', 1)
        a.put(VINDEX)
        a.label(label+'_done')
    a.get(VINDEX)
    a.branch(1, 'cpu_empty')
    head_template(a)
    a.get(VINDEX)
    a.immediate('lt', 2)
    a.branch(1, 'cpu_fail')
    a.get(HEADER)
    a.immediate('shr', 1)
    a.immediate('and', 3)
    a.immediate('eq', 3)
    a.branch(2, 'cpu_fail')
    a.get(HEADER)
    a.immediate('shr', 3)
    a.immediate('and', 7)
    a.put(TEMP)
    a.immediate('lt', 7)
    a.branch(1, 'cpu_fail')
    a.get(TEMP)
    a.immediate('eq', b.HALT)
    a.branch(2, 'cpu_static')
    a.get(TEMP)
    a.immediate('eq', b.ERROR)
    a.branch(2, 'cpu_static')
    read_virtual_metadata(a)
    for mode, label in ((b.IO, 'cpu_io'), (b.SPAN, 'cpu_span'),
                        (b.STREAM, 'cpu_stream'), (b.WORDOUT, 'cpu_wordout')):
        a.get(HEADER)
        a.immediate('shr', 3)
        a.immediate('and', 7)
        a.immediate('eq', mode)
        a.branch(2, label)
    a.branch(0, 'cpu_run')


def pending_metadata(a):
    for field, dest in (('start', VSTART), ('ret', VRET), ('index', VINDEX)):
        head_read(a, HEAD_OFFSET[field], 13, dest)
    # Preserve signed lane separately. CTRL contains buf/lane/fn/kind.
    a.get(CTRL)
    a.immediate('shr', 2)
    a.immediate('and', 31)
    a.immediate('xor', 16)
    a.immediate('sub', 16)
    a.put(LENGTH)


def seek_virtual(a, target, prefix):
    """On mismatch patch only move, preserving all pending data."""
    a.get(target)
    a.emit('SWAP')
    a.get(VADDR)
    a.emit('ALU', b.ALU['eq'])
    a.branch(2, prefix+'_at')
    a.get(target)
    a.emit('SWAP')
    a.get(VADDR)
    a.emit('ALU', b.ALU['lt'])
    a.branch(2, prefix+'_right')
    patch_move(a, 2)
    a.label(prefix+'_right')
    patch_move(a, 1)
