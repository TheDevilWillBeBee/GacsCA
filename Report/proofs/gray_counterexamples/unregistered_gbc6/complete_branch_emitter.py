    a.immediate('eq', 1)
    a.branch(2, 'span_vote_aligned')
    a.get(CTRL)
    a.immediate('shr', 11)
    a.immediate('eq', 2)
    a.branch(2, 'span_vote_unaligned')
    consume_raw_bit(a)
    a.put(TEMP)
    a.branch(0, 'span_bit_ready')
    a.label('span_vote_aligned')
    constant_store(a, ADDRESS, 1)
    a.branch(0, 'span_vote')
    a.label('span_vote_unaligned')
    constant_store(a, ADDRESS, 0)
    a.label('span_vote')
    a.call('virtual_vote')
    # Restore indices clobbered by the bounded five-column vote helper.
    pending_metadata(a)
    head_read(a, HEAD_OFFSET['a'], 20, VA)
    a.label('span_bit_ready')
    a.get(VINDEX)
    a.emit('SWAP')
    a.get(VA)
    a.emit('ALU', b.ALU['sub'])
    a.immediate('sub', 1)
    a.emit('SWAP')
    a.get(TEMP)
    a.emit('ALU', b.ALU['shl'])
    a.emit('SWAP')
    a.get(VB)
    a.emit('ALU', b.ALU['or'])
    a.put(TEMP)
    head_write(a, HEAD_OFFSET['b'], 20, TEMP)
    a.get(VINDEX)
    a.branch(1, 'span_finish')
    a.immediate('sub', 1)
    head_write(a, HEAD_OFFSET['index'], 13)
    a.literal(1+2+8*b.SPAN)
    head_write(a, 0, 6)
    a.branch(0, 'cpu_next')
    a.label('span_finish')
    head_write(a, HEAD_OFFSET['a'], 20, TEMP)
    virtual_continue(a, VRET)

    a.label('cpu_stream')
