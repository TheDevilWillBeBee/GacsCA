    a.branch(2, 'stream_lane_done')
    get_bit(a, CTRL, 1)
    a.branch(2, 'stream_guard4')
    lane_guard(a, 6)
    a.branch(0, 'stream_lane_done')
    a.label('stream_guard4')
    lane_guard(a, 4)
    a.label('stream_lane_done')
    pending_length_guard(a, b.Q, 'stream')
    get_bit(a, CTRL, 0)
    a.branch(2, 'stream_constant')
    get_bit(a, CTRL, 1)
    a.put(ADDRESS)
    a.call('virtual_vote')
    pending_metadata(a)
    a.branch(0, 'stream_bit_ready')
    a.label('stream_constant')
    get_bit(a, CTRL, 2)
    a.put(TEMP)
    a.label('stream_bit_ready')
    write_virtual_output_bit(a, TEMP)
    a.get(VINDEX)
